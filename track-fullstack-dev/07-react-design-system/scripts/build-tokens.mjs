// Generates src/styles/tokens.css from tokens/tokens.json (source of truth).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('tokens/tokens.json', root), 'utf8'));

const decl = (name, value) => `  --adf-${name}: ${value};`;

function flatten(obj, prefix = '') {
  return Object.entries(obj).flatMap(([key, value]) =>
    typeof value === 'object' ? flatten(value, `${prefix}${key}-`) : [[`${prefix}${key}`, value]],
  );
}

const base = flatten(tokens.base).map(([k, v]) => decl(k, v));
const theme = (name) => Object.entries(tokens.themes[name]).map(([k, v]) => decl(`color-${k}`, v));
const indent = (lines) => lines.map((l) => `  ${l}`);

const css = [
  '/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */',
  ':root {',
  ...base,
  '}',
  '',
  '@media (prefers-reduced-motion: reduce) {',
  '  :root {',
  ...indent(Object.keys(tokens.base.duration).map((k) => decl(`duration-${k}`, '0ms'))),
  '  }',
  '}',
  '',
  '/* Default theme follows the OS; an explicit data-theme always wins. */',
  ':root,',
  '[data-theme="light"] {',
  '  color-scheme: light;',
  ...theme('light'),
  '}',
  '',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme]) {',
  '    color-scheme: dark;',
  ...indent(theme('dark')),
  '  }',
  '}',
  '',
  '@media (prefers-contrast: more) {',
  '  :root:not([data-theme]) {',
  '    color-scheme: dark;',
  ...indent(theme('high-contrast')),
  '  }',
  '}',
  '',
  '[data-theme="dark"] {',
  '  color-scheme: dark;',
  ...theme('dark'),
  '}',
  '',
  '[data-theme="high-contrast"] {',
  '  color-scheme: dark;',
  ...theme('high-contrast'),
  '}',
  '',
].join('\n');

writeFileSync(fileURLToPath(new URL('src/styles/tokens.css', root)), css);
console.log('tokens.css generated');
